-- اسم صاحب التعليق يُؤخذ من ملفه الشخصي (يمنع انتحال الأسماء).
create or replace function public.set_comment_name()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if new.user_id is not null then
    new.user_name := coalesce(
      (select name from public.profiles where id = new.user_id),
      new.user_name
    );
  end if;
  return new;
end;
$$;

