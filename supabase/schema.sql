create or replace function public.current_profile_id()
returns bigint
language sql stable security definer
set search_path = public
as $$
  select id from public.profiles where auth_id = auth.uid() limit 1;
$$;

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where auth_id = auth.uid() and role = 'admin'
  );
$$;

-- التحقق من رقم هاتف موجود بدون كشف بقية الملفات الشخصية
create or replace function public.phone_exists(p_phone text)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.profiles where phone = p_phone);
$$;

-- إلغاء حجز من قبل صاحبه (أو المدير)
create or replace function public.cancel_booking(p_id bigint)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_owner bigint;
begin
  select customer_id into v_owner from public.bookings where id = p_id;
  if v_owner is null then
    raise exception 'الحجز غير موجود';
  end if;
  if v_owner <> public.current_profile_id() and not public.is_admin() then
    raise exception 'لا تملك صلاحية إلغاء هذا الحجز';
  end if;
  update public.bookings
     set status = 'cancelled'
   where id = p_id and status in ('pending', 'confirmed', 'in_progress');
end;
$$;

-- إعجاب / إلغاء إعجاب بمنشور
create or replace function public.toggle_post_like(p_post_id bigint, p_liked boolean)
returns void
language plpgsql security definer
set search_path = public
as $$
begin
  update public.posts
     set likes = greatest(0, likes + case when p_liked then 1 else -1 end)
   where id = p_post_id;
end;
$$;

create or replace function public.increment_worker_jobs(p_worker_id bigint)
returns void
language plpgsql security definer
set search_path = public
as $$
begin
  update public.workers set jobs_done = jobs_done + 1 where id = p_worker_id;
end;
$$;

-- زيادة عدّاد أعمال الفني عند إكمال الحجز
create or replace function public.on_booking_status_change()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if new.status = 'completed'
     and coalesce(old.status, '') <> 'completed'
     and new.worker_id is not null then
    update public.workers set jobs_done = jobs_done + 1 where id = new.worker_id;
  end if;
  return new;
end;
$$;

-- منع أي مستخدم من تغيير دوره أو ربط ملفه بحساب آخر
create or replace function public.protect_profile_fields()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if auth.uid() is not null then
    new.role := old.role;
    new.auth_id := old.auth_id;
  end if;
  return new;
end;
$$;

