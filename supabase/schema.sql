create or replace view public.profiles_view
with (security_invoker = true) as
select
  p.id, p.auth_id, p.name, p.phone,
  ''::text as password,
  p.role, p.email, p.city, p.address, p.avatar, p.created_at
from public.profiles p;

create or replace view public.services_view
with (security_invoker = true) as
select
  s.id, s.category_id, s.worker_id, s.title, s.description, s.price,
  s.duration, s.rating, s.active, s.created_at,
  c.name as category_name,
  c.color as category_color,
  c.icon as category_icon,
  w.name as worker_name,
  w.phone as worker_phone
from public.services s
left join public.categories c on c.id = s.category_id
left join public.workers w on w.id = s.worker_id;

create or replace view public.bookings_view
with (security_invoker = true) as
select
  b.id, b.customer_id, b.service_id, b.worker_id, b.scheduled_at, b.slot,
  b.address, b.notes, b.status, b.payment_method, b.total, b.created_at,
  s.title as service_title,
  w.name as worker_name,
  w.phone as worker_phone,
  u.name as customer_name,
  u.phone as customer_phone
from public.bookings b
left join public.services s on s.id = b.service_id
left join public.workers w on w.id = b.worker_id
left join public.profiles u on u.id = b.customer_id;

-- عرض المنشورات: يظهر المعتمد للجميع، وغير المعتمد للمدير فقط.
create or replace view public.posts_view as
select
  p.id, p.customer_id, p.category_id, p.title, p.description, p.price,
  p.media, p.media_type, p.location, p.approved, p.likes, p.created_at,
  u.name as customer_name,
  u.phone as customer_phone,
  c.name as category_name,
  (select count(*) from public.comments cm where cm.post_id = p.id) as comment_count
from public.posts p
left join public.profiles u on u.id = p.customer_id
left join public.categories c on c.id = p.category_id
where p.approved = 1 or public.is_admin();

create or replace view public.comments_view
with (security_invoker = true) as
select
  cm.id, cm.post_id, cm.user_id, cm.user_name, cm.body, cm.created_at,
  u.avatar as avatar
from public.comments cm
left join public.profiles u on u.id = cm.user_id;

create or replace view public.receipts_view
with (security_invoker = true) as
select
  r.id, r.invoice_no, r.booking_id, r.user_id, r.title, r.amount, r.method,
  r.card_brand, r.last4, r.paid, r.created_at,
  b.worker_id as worker_id,
  s.title as service_title,
  w.name as worker_name,
  u.name as customer_name,
  u.phone as customer_phone
from public.receipts r
left join public.bookings b on b.id = r.booking_id
left join public.services s on s.id = b.service_id
left join public.workers w on w.id = b.worker_id
left join public.profiles u on u.id = r.user_id;

-- محادثات الدعم: المدير يرى الكل، والزبون يرى محادثته فقط.
create or replace view public.threads_view as
select
  m.thread_id,
  u.name as customer_name,
  u.phone as customer_phone,
  (select m2.body from public.messages m2
    where m2.thread_id = m.thread_id order by m2.created_at desc limit 1) as last_message,
  (select m3.created_at from public.messages m3
    where m3.thread_id = m.thread_id order by m3.created_at desc limit 1) as last_at,
  (select count(*) from public.messages m4
    where m4.thread_id = m.thread_id and m4.sender_role = 'customer' and m4.read = 0) as unread
from public.messages m
left join public.profiles u on u.id = m.thread_id
where public.is_admin() or m.thread_id = public.current_profile_id()
group by m.thread_id, u.name, u.phone;

