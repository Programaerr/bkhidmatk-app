-- ---------------------------------------------------------------- profiles
create table if not exists public.profiles (
  id          bigint generated by default as identity primary key,
  auth_id     uuid unique references auth.users (id) on delete cascade,
  name        text not null,
  phone       text not null unique,
  role        text not null default 'customer' check (role in ('customer', 'admin')),
  email       text,
  city        text,
  address     text,
  avatar      text,
  created_at  timestamptz not null default now()
);

create index if not exists profiles_auth_idx on public.profiles (auth_id);
create index if not exists profiles_phone_idx on public.profiles (phone);

-- -------------------------------------------------------------- categories
create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null,
  icon        text not null default 'build',
  color       bigint not null default 4294951175,
  sort_order  integer not null default 0
);

-- ----------------------------------------------------------------- workers
create table if not exists public.workers (
  id           bigint generated by default as identity primary key,
  name         text not null,
  phone        text not null,
  specialty    text not null,
  category_id  bigint references public.categories (id) on delete set null,
  rating       double precision not null default 4.8,
  jobs_done    integer not null default 0,
  bio          text,
  avatar       text,
  available    smallint not null default 1
);

-- ---------------------------------------------------------------- services
create table if not exists public.services (
  id           bigint generated by default as identity primary key,
  category_id  bigint references public.categories (id) on delete set null,
  worker_id    bigint references public.workers (id) on delete set null,
  title        text not null,
  description  text not null default '',
  price        double precision not null default 0,
  duration     integer not null default 60,
  rating       double precision not null default 4.8,
  active       smallint not null default 1,
  created_at   timestamptz not null default now()
);

-- ---------------------------------------------------------------- bookings
create table if not exists public.bookings (
  id              bigint generated by default as identity primary key,
  customer_id     bigint not null references public.profiles (id) on delete cascade,
  service_id      bigint references public.services (id) on delete set null,
  worker_id       bigint references public.workers (id) on delete set null,
  scheduled_at    timestamptz not null default now(),
  slot            text not null default '09:00',
  address         text not null default '',
  notes           text,
  status          text not null default 'pending'
                    check (status in ('pending', 'confirmed', 'in_progress', 'completed', 'cancelled')),
  payment_method  text not null default 'cash' check (payment_method in ('cash', 'card')),
  total           double precision not null default 0,
  created_at      timestamptz not null default now()
);

create index if not exists bookings_customer_idx on public.bookings (customer_id);
create index if not exists bookings_status_idx on public.bookings (status);

-- ------------------------------------------------------------------- posts
create table if not exists public.posts (
  id           bigint generated by default as identity primary key,
  customer_id  bigint not null references public.profiles (id) on delete cascade,
  category_id  bigint references public.categories (id) on delete set null,
  title        text not null,
  description  text not null default '',
  price        double precision not null default 0,
  media        text,
  media_type   text not null default 'none' check (media_type in ('image', 'video', 'none')),
  location     text,
  approved     smallint not null default 1,
  likes        integer not null default 0,
  created_at   timestamptz not null default now()
);

create index if not exists posts_created_idx on public.posts (created_at desc);

-- ---------------------------------------------------------------- comments
create table if not exists public.comments (
  id          bigint generated by default as identity primary key,
  post_id     bigint not null references public.posts (id) on delete cascade,
  user_id     bigint references public.profiles (id) on delete set null,
  user_name   text not null,
  body        text not null,
  created_at  timestamptz not null default now()
);

create index if not exists comments_post_idx on public.comments (post_id);

-- ---------------------------------------------------------------- messages
create table if not exists public.messages (
  id           bigint generated by default as identity primary key,
  thread_id    bigint not null references public.profiles (id) on delete cascade,
  sender_id    bigint references public.profiles (id) on delete set null,
  sender_role  text not null check (sender_role in ('customer', 'admin')),
  body         text not null,
  created_at   timestamptz not null default now(),
  read         smallint not null default 0
);

create index if not exists messages_thread_idx on public.messages (thread_id, created_at);

-- ------------------------------------------------------------------- cards
create table if not exists public.cards (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.profiles (id) on delete cascade,
  brand       text not null default 'Card',
  last4       text not null default '0000',
  holder      text not null default '',
  expiry      text not null default '',
  is_default  smallint not null default 0
);

-- ---------------------------------------------------------------- receipts
create table if not exists public.receipts (
  id          bigint generated by default as identity primary key,
  invoice_no  text not null,
  booking_id  bigint references public.bookings (id) on delete set null,
  user_id     bigint references public.profiles (id) on delete set null,
  title       text not null default 'وصل خدمة',
  amount      double precision not null default 0,
  method      text not null default 'cash' check (method in ('cash', 'card')),
  card_brand  text,
  last4       text,
  paid        smallint not null default 0,
  created_at  timestamptz not null default now()
