create or replace function public.submit_craftsman_application(
  p_name text,
  p_phone text,
  p_age integer,
  p_city text,
  p_address text,
  p_trade text,
  p_experience_years integer,
  p_about text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  application_id bigint;
  local_phone text := public.normalize_iraqi_phone(coalesce(p_phone, ''));
begin
  if char_length(trim(coalesce(p_name, ''))) not between 3 and 120
     or local_phone !~ '^07[0-9]{9}$'
     or p_age not between 16 and 80
     or char_length(trim(coalesce(p_city, ''))) not between 2 and 100
     or char_length(trim(coalesce(p_trade, ''))) not between 2 and 120
     or p_experience_years not between 0 and 60
     or char_length(coalesce(p_address, '')) > 500
     or char_length(coalesce(p_about, '')) > 2000 then
    raise exception 'Application details are invalid';
  end if;
  if exists (
    select 1 from public.craftsman_applications a
     where a.phone = local_phone and a.status = 'pending'
  ) then
    raise exception 'A pending application already exists for this phone';
  end if;

  insert into public.craftsman_applications(
    name, phone, age, city, address, trade, experience_years, about
  ) values (
    trim(p_name), local_phone, p_age, trim(p_city),
    nullif(trim(p_address), ''), trim(p_trade), p_experience_years,
    nullif(trim(p_about), '')
  )
  returning id into application_id;
  return application_id;
end
$$;

create or replace function public.has_pending_craftsman_application(p_phone text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.normalize_iraqi_phone(coalesce(p_phone, '')) ~ '^07[0-9]{9}$'
     and exists (
       select 1 from public.craftsman_applications a
        where a.phone = public.normalize_iraqi_phone(p_phone)
          and a.status = 'pending'
     )
$$;

create or replace function public.accept_craftsman_application(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  application_row public.craftsman_applications%rowtype;
begin
  if not public.is_app_admin() then
    raise exception 'Only administrators can accept applications'
      using errcode = '42501';
  end if;
  select * into application_row
    from public.craftsman_applications
   where id = p_application_id for update;
  if not found or application_row.status <> 'pending' then
    raise exception 'Pending application not found';
  end if;
  insert into public.hire_phones(phone, note)
  values (application_row.phone, application_row.trade)
  on conflict (phone) do update set note = excluded.note;
  update public.craftsman_applications
     set status = 'accepted' where id = p_application_id;
end
$$;

create or replace function public.reject_craftsman_application(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_app_admin() then
    raise exception 'Only administrators can reject applications'
      using errcode = '42501';
  end if;
  update public.craftsman_applications
     set status = 'rejected'
   where id = p_application_id and status = 'pending';
  if not found then raise exception 'Pending application not found'; end if;
end
$$;

create or replace function public.send_app_notification(
  p_audience text,
  p_phone text,
  p_title text,
  p_body text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  sender_id bigint;
  inserted_count integer;
begin
  select p.id into sender_id
    from public.app_profiles p
   where p.auth_user_id = auth.uid()
     and public.is_app_admin();
  if sender_id is null then
    raise exception 'Only administrators can send notifications'
      using errcode = '42501';
  end if;
  if p_audience is null or p_audience not in ('all', 'customer', 'worker', 'phone') then
    raise exception 'Invalid notification audience';
  end if;
  if nullif(trim(p_title), '') is null or char_length(p_title) > 120
     or nullif(trim(p_body), '') is null or char_length(p_body) > 2000 then
    raise exception 'Notification title or message is invalid';
  end if;
  if p_audience = 'phone' and public.normalize_iraqi_phone(coalesce(p_phone, '')) !~ '^07[0-9]{9}$' then
    raise exception 'A valid Iraqi mobile number is required';
  end if;

  insert into public.app_notifications(recipient_id, sender_auth_id, title, body)
  select p.id, auth.uid(), trim(p_title), trim(p_body)
    from public.app_profiles p
   where p_audience = 'all'
      or (p_audience = 'customer' and p.role = 'customer')
      or (p_audience = 'worker' and p.role = 'worker')
      or (p_audience = 'phone' and p.phone = public.normalize_iraqi_phone(p_phone));

  get diagnostics inserted_count = row_count;
  if p_audience = 'phone' and inserted_count = 0 then
    raise exception 'No registered account was found for this phone number';
  end if;
  return inserted_count;
end
$$;

