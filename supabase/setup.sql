create or replace function public.normalize_iraqi_phone(p_phone text)
returns text
language sql
immutable
strict
as $$
  select case
    when regexp_replace(p_phone, '[^0-9+]', '', 'g') like '+964%'
      then '0' || substr(regexp_replace(p_phone, '[^0-9]', '', 'g'), 4)
    when regexp_replace(p_phone, '[^0-9]', '', 'g') like '964%'
      then '0' || substr(regexp_replace(p_phone, '[^0-9]', '', 'g'), 4)
    else regexp_replace(p_phone, '[^0-9]', '', 'g')
  end
$$;

