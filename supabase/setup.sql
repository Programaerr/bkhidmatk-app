  nullif(u.raw_user_meta_data ->> 'city', ''),
  nullif(u.raw_user_meta_data ->> 'address', '')
from auth.users u
cross join lateral (
  select public.normalize_iraqi_phone(
    coalesce(u.raw_user_meta_data ->> 'app_phone', u.phone, '')
  ) as phone
) p
where p.phone ~ '^07[0-9]{9}$'
on conflict (auth_user_id) do nothing;

