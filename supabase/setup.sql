create extension if not exists pgcrypto;

create or replace function public.normalize_iraqi_phone(p_phone text)
returns text
language sql
immutable
strict
as $$
  select case
    when regexp_replace(p_phone, '[^0-9+]', '', 'g') like '+964%'
      then '0' || substr(regexp_replace(p_phone, '[^0-9]', '', 'g'), 4)
    when regexp_replace(p_phone, '[^0-9]', '', 'g') like '964%'
      then '0' || substr(regexp_replace(p_phone, '[^0-9]', '', 'g'), 4)
    else regexp_replace(p_phone, '[^0-9]', '', 'g')
  end
$$;

create table if not exists public.app_profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null default '',
  phone text not null unique,
  role text not null default 'customer'
    check (role in ('customer', 'worker', 'admin')),
  city text,
  address text,
  avatar text,
  points integer not null default 0 check (points >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.hire_phones (
  id bigint generated by default as identity primary key,
  phone text not null unique,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.app_notifications (
  id bigint generated by default as identity primary key,
  recipient_id bigint not null references public.app_profiles(id) on delete cascade,
  sender_auth_id uuid not null references auth.users(id) on delete restrict,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 2000),
  sent_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists app_notifications_recipient_sent_idx
  on public.app_notifications(recipient_id, sent_at desc);
create index if not exists app_profiles_role_idx on public.app_profiles(role);

