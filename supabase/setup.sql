create or replace function public.create_app_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  local_phone text;
  assigned_role text := 'customer';
begin
  local_phone := public.normalize_iraqi_phone(
    coalesce(new.raw_user_meta_data ->> 'app_phone', new.phone, '')
  );
  if local_phone !~ '^07[0-9]{9}$' then
    raise exception 'A valid Iraqi mobile number is required';
  end if;

  if exists (
    select 1 from public.admin_users a where a.auth_user_id = new.id
  ) then
    assigned_role := 'admin';
  elsif exists (
    select 1 from public.hire_phones h
    where public.normalize_iraqi_phone(h.phone) = local_phone
  ) then
    assigned_role := 'worker';
  end if;

  insert into public.app_profiles (
    auth_user_id, name, phone, role, city, address
  ) values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), local_phone),
    local_phone,
    assigned_role,
    nullif(new.raw_user_meta_data ->> 'city', ''),
    nullif(new.raw_user_meta_data ->> 'address', '')
  )
  on conflict (auth_user_id) do update set
    name = case when app_profiles.name = '' then excluded.name else app_profiles.name end,
    phone = excluded.phone;
  return new;
end
$$;

