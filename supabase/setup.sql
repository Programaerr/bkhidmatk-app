create or replace function public.update_booking_status(p_booking_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  assigned_worker bigint;
  old_status text;
begin
  if not public.is_app_admin() then
    raise exception 'Only administrators can update bookings'
      using errcode = '42501';
  end if;
  if p_status not in ('pending', 'confirmed', 'in_progress', 'completed', 'cancelled') then
    raise exception 'Invalid booking status';
  end if;
  select worker_id, status into assigned_worker, old_status
    from public.bookings where id = p_booking_id for update;
  if not found then raise exception 'Booking not found'; end if;
  update public.bookings set status = p_status where id = p_booking_id;
  if p_status = 'completed' and old_status <> 'completed' and assigned_worker is not null then
    update public.workers set jobs_done = jobs_done + 1 where id = assigned_worker;
  end if;
end
$$;

