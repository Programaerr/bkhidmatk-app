grant select on public.app_notifications to authenticated;
grant update (read_at) on public.app_notifications to authenticated;
grant usage, select on sequence public.hire_phones_id_seq to authenticated;
revoke all on function public.send_app_notification(text, text, text, text) from public, anon;
grant execute on function public.send_app_notification(text, text, text, text) to authenticated;
revoke all on function public.normalize_iraqi_phone(text) from public, anon;
grant execute on function public.normalize_iraqi_phone(text) to authenticated;
