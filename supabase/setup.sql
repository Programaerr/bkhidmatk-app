create or replace function public.set_post_like(p_post_id bigint, p_liked boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_id bigint := public.current_app_profile_id();
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  if not exists (
    select 1 from public.posts p
     where p.id = p_post_id
       and (p.approved or p.customer_id = profile_id or public.is_app_admin())
  ) then
    raise exception 'Post not found or not available';
  end if;
  if p_liked then
    insert into public.post_likes(post_id, user_id) values (p_post_id, profile_id)
    on conflict do nothing;
  else
    delete from public.post_likes where post_id = p_post_id and user_id = profile_id;
  end if;
  update public.posts p
     set likes = (select count(*)::integer from public.post_likes l where l.post_id = p_post_id)
   where p.id = p_post_id;
end
$$;

