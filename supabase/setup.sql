select
  u.id,
  coalesce(nullif(trim(u.raw_user_meta_data ->> 'name'), ''), p.phone),
  p.phone,
  case
    when exists (
      select 1 from public.admin_users a where a.auth_user_id = u.id
    ) then 'admin'
    when exists (
    select 1 from public.hire_phones h
     where public.normalize_iraqi_phone(h.phone) = p.phone
