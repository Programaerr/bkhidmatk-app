create or replace function public.create_app_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  local_phone text;
  assigned_role text := 'customer';
begin
  local_phone := public.normalize_iraqi_phone(
    coalesce(new.raw_user_meta_data ->> 'app_phone', new.phone, '')
  );
  if local_phone !~ '^07[0-9]{9}$' then
    raise exception 'A valid Iraqi mobile number is required';
  end if;

  if exists (
    select 1 from public.hire_phones h
    where public.normalize_iraqi_phone(h.phone) = local_phone
  ) then
    assigned_role := 'worker';
  end if;

  insert into public.app_profiles (
    auth_user_id, name, phone, role, city, address
  ) values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), local_phone),
    local_phone,
    assigned_role,
    nullif(new.raw_user_meta_data ->> 'city', ''),
    nullif(new.raw_user_meta_data ->> 'address', '')
  )
  on conflict (auth_user_id) do update set
    name = case when app_profiles.name = '' then excluded.name else app_profiles.name end,
    phone = excluded.phone;
  return new;
end
$$;

drop trigger if exists on_auth_user_created_jaik on auth.users;
create trigger on_auth_user_created_jaik
  after insert on auth.users
  for each row execute function public.create_app_profile();

insert into public.app_profiles (
  auth_user_id, name, phone, role, city, address
)
select
  u.id,
  coalesce(nullif(trim(u.raw_user_meta_data ->> 'name'), ''), p.phone),
  p.phone,
  case when exists (
    select 1 from public.hire_phones h
     where public.normalize_iraqi_phone(h.phone) = p.phone
  ) then 'worker' else 'customer' end,
  nullif(u.raw_user_meta_data ->> 'city', ''),
  nullif(u.raw_user_meta_data ->> 'address', '')
from auth.users u
cross join lateral (
  select public.normalize_iraqi_phone(
    coalesce(u.raw_user_meta_data ->> 'app_phone', u.phone, '')
  ) as phone
) p
where p.phone ~ '^07[0-9]{9}$'
on conflict (auth_user_id) do nothing;

create or replace function public.promote_hired_phone()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.app_profiles
     set role = 'worker'
   where phone = public.normalize_iraqi_phone(new.phone)
     and role = 'customer';
  return new;
end
$$;

drop trigger if exists on_hire_phone_added_jaik on public.hire_phones;
create trigger on_hire_phone_added_jaik
  after insert or update of phone on public.hire_phones
  for each row execute function public.promote_hired_phone();

create or replace function public.revert_deleted_hire_phone()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.app_profiles p
     set role = 'customer'
   where p.phone = public.normalize_iraqi_phone(old.phone)
     and p.role = 'worker'
     and not exists (
       select 1 from public.hire_phones h
        where public.normalize_iraqi_phone(h.phone) = p.phone
     );
  return old;
end
$$;

drop trigger if exists on_hire_phone_deleted_jaik on public.hire_phones;
create trigger on_hire_phone_deleted_jaik
  after delete on public.hire_phones
  for each row execute function public.revert_deleted_hire_phone();

create or replace function public.is_app_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.app_profiles p
     where p.auth_user_id = auth.uid() and p.role = 'admin'
  )
$$;

create or replace function public.send_app_notification(
  p_audience text,
  p_phone text,
  p_title text,
  p_body text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  sender_id bigint;
  inserted_count integer;
begin
  select p.id into sender_id
    from public.app_profiles p
   where p.auth_user_id = auth.uid()
     and p.role = 'admin';
  if sender_id is null then
    raise exception 'Only administrators can send notifications'
      using errcode = '42501';
  end if;
  if p_audience is null or p_audience not in ('all', 'customer', 'worker', 'phone') then
    raise exception 'Invalid notification audience';
  end if;
  if nullif(trim(p_title), '') is null or char_length(p_title) > 120
     or nullif(trim(p_body), '') is null or char_length(p_body) > 2000 then
    raise exception 'Notification title or message is invalid';
  end if;
  if p_audience = 'phone' and public.normalize_iraqi_phone(coalesce(p_phone, '')) !~ '^07[0-9]{9}$' then
    raise exception 'A valid Iraqi mobile number is required';
  end if;

  insert into public.app_notifications(recipient_id, sender_auth_id, title, body)
  select p.id, auth.uid(), trim(p_title), trim(p_body)
    from public.app_profiles p
   where p_audience = 'all'
      or (p_audience = 'customer' and p.role = 'customer')
      or (p_audience = 'worker' and p.role = 'worker')
      or (p_audience = 'phone' and p.phone = public.normalize_iraqi_phone(p_phone));

  get diagnostics inserted_count = row_count;
  if p_audience = 'phone' and inserted_count = 0 then
    raise exception 'No registered account was found for this phone number';
  end if;
  return inserted_count;
end
$$;

alter table public.app_profiles enable row level security;
alter table public.hire_phones enable row level security;
alter table public.app_notifications enable row level security;

drop policy if exists "profiles_read_self_or_admin" on public.app_profiles;
create policy "profiles_read_self_or_admin" on public.app_profiles
  for select to authenticated
  using (auth_user_id = (select auth.uid()) or (select public.is_app_admin()));

drop policy if exists "profiles_update_self" on public.app_profiles;
create policy "profiles_update_self" on public.app_profiles
  for update to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

drop policy if exists "hire_phones_admin_only" on public.hire_phones;
create policy "hire_phones_admin_only" on public.hire_phones
  for all to authenticated
  using ((select public.is_app_admin()))
  with check ((select public.is_app_admin()));

drop policy if exists "notifications_read_recipient_or_sender" on public.app_notifications;
create policy "notifications_read_recipient_or_sender" on public.app_notifications
  for select to authenticated
  using (
    exists (select 1 from public.app_profiles p
             where p.id = recipient_id and p.auth_user_id = (select auth.uid()))
    or sender_auth_id = (select auth.uid())
  );

drop policy if exists "notifications_mark_own_read" on public.app_notifications;
create policy "notifications_mark_own_read" on public.app_notifications
  for update to authenticated
  using (
    exists (select 1 from public.app_profiles p
             where p.id = recipient_id and p.auth_user_id = (select auth.uid()))
  )
  with check (
    exists (select 1 from public.app_profiles p
             where p.id = recipient_id and p.auth_user_id = (select auth.uid()))
  );

revoke all on public.app_profiles, public.hire_phones, public.app_notifications from anon;
