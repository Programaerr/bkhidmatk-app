create or replace function public.list_admin_workers(p_worker_id bigint default null)
returns table (
  id bigint,
  name text,
  phone text,
  specialty text,
  category_id bigint,
  rating double precision,
  jobs_done integer,
  bio text,
  avatar text,
  available boolean,
  city text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_app_admin() then
    raise exception 'Only administrators can view worker phone numbers'
      using errcode = '42501';
  end if;
  return query
    select w.id, w.name, w.phone, w.specialty, w.category_id,
           w.rating, w.jobs_done, w.bio, w.avatar, w.available, w.city
      from public.workers w
     where p_worker_id is null or w.id = p_worker_id
     order by w.rating desc;
end
$$;

revoke all on function public.list_admin_workers(bigint) from public, anon;
grant execute on function public.list_admin_workers(bigint) to authenticated;

-- 5) الحرفي يغيّر محافظته من ملفه الشخصي.
create or replace function public.update_my_worker_city(p_city text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_phone text;
  local_city text := trim(coalesce(p_city, ''));
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if char_length(local_city) not between 2 and 100 then
    raise exception 'Invalid governorate';
  end if;
  select p.phone into profile_phone
    from public.app_profiles p
   where p.auth_user_id = auth.uid()
     and p.role = 'worker';
  if profile_phone is null then
    raise exception 'Profile not found';
  end if;
  update public.workers w
     set city = local_city
   where w.phone = profile_phone;
  update public.app_profiles p
     set city = local_city
   where p.phone = profile_phone;
end
$$;

revoke all on function public.update_my_worker_city(text) from public, anon;
grant execute on function public.update_my_worker_city(text) to authenticated;

-- الحرفي يقرأ ملفه من الدليل (محافظته) دون كشف أرقام هواتف بقية الحرفيين.
create or replace function public.my_worker_profile(p_phone text)
returns table (
  id bigint,
  name text,
  specialty text,
  category_id bigint,
  rating double precision,
  jobs_done integer,
  bio text,
  avatar text,
  available boolean,
  city text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  return query
    select w.id, w.name, w.specialty, w.category_id, w.rating,
           w.jobs_done, w.bio, w.avatar, w.available, w.city
      from public.workers w
      join public.app_profiles p on p.phone = w.phone
     where p.auth_user_id = auth.uid()
       and p.role = 'worker'
       and p.phone = public.normalize_iraqi_phone(coalesce(p_phone, ''))
     limit 1;
end
$$;

revoke all on function public.my_worker_profile(text) from public, anon;
grant execute on function public.my_worker_profile(text) to authenticated;

-- 6) قبول طلب الحرفي: ينشئ ملفه في دليل محافظته إن لم يكن موجوداً.
create or replace function public.accept_craftsman_application(p_application_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  application_row public.craftsman_applications%rowtype;
begin
  if not public.is_app_admin() then
    raise exception 'Only administrators can accept applications'
      using errcode = '42501';
  end if;
  select * into application_row
    from public.craftsman_applications
   where id = p_application_id for update;
  if not found or application_row.status <> 'pending' then
    raise exception 'Pending application not found';
  end if;

  insert into public.workers(name, phone, specialty, city, available)
  values (
    application_row.name,
    application_row.phone,
    application_row.trade,
    application_row.city,
    true
  )
  on conflict (phone) do nothing;

  update public.workers w
     set city = application_row.city
   where w.phone = application_row.phone
     and (w.city is null or trim(w.city) = '');

  update public.app_profiles p
     set city = application_row.city
   where p.phone = application_row.phone
     and (p.city is null or trim(p.city) = '');

  insert into public.hire_phones(phone, note)
  values (application_row.phone, application_row.trade)
  on conflict (phone) do update set note = excluded.note;

  update public.craftsman_applications
     set status = 'accepted' where id = p_application_id;
end
$$;

revoke all on function public.accept_craftsman_application(bigint)
  from public, anon, authenticated;
grant execute on function public.accept_craftsman_application(bigint)
  to authenticated;

