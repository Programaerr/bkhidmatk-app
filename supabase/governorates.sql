-- ملف كل محافظة: اسم المحافظة وعدد حرفييها المتاحين.
create or replace view public.governorate_profiles
with (security_invoker = true) as
select
  g.id,
  g.name,
  g.name_en,
  g.sort_order,
  g.active,
  count(w.id)::integer as total_workers,
  count(w.id) filter (where w.available)::integer as available_workers
from public.governorates g
left join public.workers w on w.city = g.name
group by g.id, g.name, g.name_en, g.sort_order, g.active;

revoke all on public.governorate_profiles from public, anon, authenticated;
grant select on public.governorate_profiles to anon, authenticated;

