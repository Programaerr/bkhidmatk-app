-- تفعيل إضافة UUID لإنشاء معرفات فريدة (يُوصى بها في Supabase)
create extension if not exists "pgcrypto";

-- ----------------------------------------------------
--  1. جدول المستخدمين (العملاء، المدير، الحرفيون)
-- ----------------------------------------------------
create table if not exists users (
  id bigint generated by default as identity primary key,
  uuid uuid not null default gen_random_uuid() unique,
  name text not null,
  phone text not null unique,
  password_hash text not null,
  role text not null default 'customer' check (role in ('customer','admin','worker')),
  email text,
  city text,
  address text,
  avatar_url text,
  created_at timestamptz not null default now()
);

-- فهرس سريع للبحث بالهاتف (يستخدم عند تسجيل الدخول والتعرف على المدير)
create index if not exists idx_users_phone on users(phone);
create index if not exists idx_users_role on users(role);

-- ----------------------------------------------------
--  2. الفئات (كهرباء، سباكة، صباغة...)
-- ----------------------------------------------------
create table if not exists categories (
  id bigint generated by default as identity primary key,
  name text not null,
  icon text not null,
  color integer not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  3. الحرفيون (ملف العامل)
-- ----------------------------------------------------
create table if not exists workers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  specialty text not null,
  category_id bigint references categories(id) on delete set null,
  rating double precision not null default 4.8,
  jobs_done integer not null default 0,
  bio text,
  avatar_url text,
  available boolean not null default true,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  4. الخدمات
-- ----------------------------------------------------
create table if not exists services (
  id bigint generated by default as identity primary key,
  category_id bigint not null references categories(id) on delete cascade,
  worker_id bigint references workers(id) on delete set null,
  title text not null,
  description text not null,
  price real not null,
  duration integer not null default 60,
  rating double precision not null default 4.8,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  5. الحجوزات
-- ----------------------------------------------------
create table if not exists bookings (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references users(id) on delete cascade,
  service_id bigint not null references services(id) on delete cascade,
  worker_id bigint references workers(id) on delete set null,
  scheduled_at timestamptz not null,
  slot text not null,
  address text not null,
  notes text,
  status text not null default 'pending' check (status in ('pending','confirmed','completed','cancelled')),
  payment_method text not null default 'cash',
  total real not null,
  rating integer,
  review text,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  6. التوظيف عبر رقم الهاتف (يشغل صلاحية «حرفي» للمدير)
-- ----------------------------------------------------
create table if not exists hires (
  id bigint generated by default as identity primary key,
  phone text not null unique,
  note text,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  7. طلبات انضمام الحرفيين من الشاشة الأولى
-- ----------------------------------------------------
create table if not exists craftsman_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  age integer not null,
  city text not null,
  address text,
  trade text not null,
  experience_years integer not null,
  about text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  8. قسم «أعمالنا» (فيديوهات المدير)
-- ----------------------------------------------------
create table if not exists our_works (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  video_url text not null,
  active boolean not null default true,
  views bigint not null default 0,
  likes bigint not null default 0,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  9. تعليقات على أعمالنا
-- ----------------------------------------------------
create table if not exists work_comments (
  id bigint generated by default as identity primary key,
  work_id bigint not null references our_works(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  user_name text not null,
  body text not null,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  10. إعجابات أعمالنا
-- ----------------------------------------------------
create table if not exists work_likes (
  work_id bigint not null references our_works(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (work_id, user_id)
);

-- ----------------------------------------------------
--  11. الرسائل (الدردشة مع الشركة فقط)
-- ----------------------------------------------------
create table if not exists messages (
  id bigint generated by default as identity primary key,
  thread_id bigint not null,
  sender_id bigint not null references users(id) on delete cascade,
  sender_role text not null,
  body text not null,
  created_at timestamptz not null default now(),
  read boolean not null default false
);

-- ----------------------------------------------------
--  12. الإشعارات (جديد — للإشعارات من لوحة المدير)
-- ----------------------------------------------------
create table if not exists notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  target_role text not null check (target_role in ('all','customer','worker','admin')),
  target_phone text, -- إذا أُريد إرسال لشخص معين برقم هاتفه
  sent_by bigint references users(id) on delete set null,
  sent_at timestamptz not null default now(),
  read boolean not null default false,
  data jsonb default '{}'::jsonb -- بيانات إضافية (رابط، معرف حجز، إلخ)
);

create index if not exists idx_notifications_target on notifications(target_role);
create index if not exists idx_notifications_sent_at on notifications(sent_at desc);

-- ----------------------------------------------------
--  13. البطاقات (الدفع التجريبي)
-- ----------------------------------------------------
create table if not exists cards (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  brand text not null,
  last4 text not null,
  holder text not null,
  expiry text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  14. الوصلات الإلكترونية
-- ----------------------------------------------------
create table if not exists receipts (
  id bigint generated by default as identity primary key,
  invoice_no text not null,
  booking_id bigint references bookings(id) on delete set null,
  user_id bigint not null references users(id) on delete cascade,
  title text not null,
  amount real not null,
  method text not null,
  card_brand text,
  last4 text,
  paid boolean not null default false,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  15. الإعدادات (مفتاح، قيمة)
-- ----------------------------------------------------
create table if not exists settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

-- ----------------------------------------------------
--  16. منشورات العملاء (محذوفة من واجهة التطبيق، maar البيانات محفوظة)
-- ----------------------------------------------------
create table if not exists posts (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references users(id) on delete cascade,
  category_id bigint not null references categories(id) on delete cascade,
  title text not null,
  description text not null,
  price real not null,
  media text,
  media_type text not null default 'none',
  location text,
  approved boolean not null default true,
  likes bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references posts(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  user_name text not null,
  body text not null,
  created_at timestamptz not null default now()
);

