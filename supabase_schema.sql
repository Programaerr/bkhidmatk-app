-- كتابة خاصة للمستخدم المسجل فقط على بياناته
create policy "المستخدم modifies بياناته الخاصة" on users for all using (auth.uid()::text = id::text);
create policy "المستخدم modifies حجوزاته الخاصة" on bookings for all using (auth.uid()::text = customer_id::text);
create policy "المستخدم modifies إشعاراته الخاصة" on notifications for all using (true);
create policy "المستخدم modifies بطاقاته الخاصة" on cards for all using (auth.uid()::text = user_id::text);
create policy "المستخدم modifies وصولاته الخاصة" on receipts for all using (auth.uid()::text = user_id::text);

-- الإدارة: المدير له كل الصلاحيات على كل شيء
create policy "المدير له صلاحيات كاملة" on all tables in schema public for all using (
  exists (select 1 from users where id = auth.uid()::bigint and role = 'admin')
);

-- =====================================================================
--  دالة تلقائية: عند إضافة سجل في جدول «التوظيف» برقم هاتف مسجل،
--  يُرقّى المستخدم تلقائياً إلى role = 'worker'
-- =====================================================================
create or replace function upgrade_user_to_worker_on_hire()
returns trigger language plpgsql as $$
begin
  update users
  set role = 'worker'
  where phone = new.phone;
  return new;
end;
$$;

create trigger trigger_upgrade_user_to_worker_on_hire
after insert on hires
for each row
execute function upgrade_user_to_worker_on_hire();

